const STRINGS: Record<PortalLanguage, PortalStrings> = { en, es, fr, it, pt, de };

export function portalLanguageOf(value?: string | null): PortalLanguage {
  return value && value in STRINGS ? (value as PortalLanguage) : 'en';
}

export function portalStrings(language?: string | null): PortalStrings {
  return STRINGS[portalLanguageOf(language)];
}

/** Fills {name} placeholders, e.g. fill(t.stepOf, { step: 2 }). */
export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key) => (key in values ? String(values[key]) : match));
}
